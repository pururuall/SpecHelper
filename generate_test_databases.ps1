function Create-CatalogFile($filePath, $data) {
    if (Test-Path $filePath) { Remove-Item $filePath -Force }
    $wb = $excel.Workbooks.Add()
    $ws = $wb.Worksheets.Item(1)
    $ws.Name = "Справочник"
    
    # Headers
    $headers = @("Обозначение", "Наименование", "Папка")
    for ($c = 0; $c -lt $headers.Count; $c++) {
        $cell = $ws.Cells.Item(1, $c + 1)
        $cell.Value2 = $headers[$c]
        $cell.Font.Bold = $true
        $cell.Interior.Color = 14277081 # Light gray
    }
    
    # Data rows
    for ($r = 0; $r -lt $data.Count; $r++) {
        $row = $data[$r]
        $ws.Cells.Item($r + 2, 1).Value2 = $row[0]
        $ws.Cells.Item($r + 2, 2).Value2 = $row[1]
        $ws.Cells.Item($r + 2, 3).Value2 = $row[2]
    }
    
    $ws.Columns.AutoFit() | Out-Null
    $wb.SaveAs($filePath, 51) # 51 = xlOpenXMLWorkbook (.xlsx)
    $wb.Close($false)
    [System.Runtime.InteropServices.Marshal]::ReleaseComObject($ws) | Out-Null
    [System.Runtime.InteropServices.Marshal]::ReleaseComObject($wb) | Out-Null
    Write-Host "Создан файл: $filePath (записей: $($data.Count))"
}

